"use client";

import type { StudioState } from "@/store/useStudioStore";
import { CHARSETS } from "@/engine/asciiAtlas";

const escapeHtml = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export function exportAsciiHtml(state: StudioState, source: HTMLCanvasElement, cols = 120): string {
  const aspect = source.height / source.width;
  const rows = Math.max(8, Math.round(cols * aspect * 0.5)); // glyph cells are ~2× tall
  const c = document.createElement("canvas");
  c.width = cols;
  c.height = rows;
  const ctx = c.getContext("2d", { willReadFrequently: true })!;
  const scale = Math.max(cols / source.width, rows / source.height);
  ctx.drawImage(
    source,
    (cols - source.width * scale) / 2,
    (rows - source.height * scale) / 2,
    source.width * scale,
    source.height * scale,
  );
  const d = ctx.getImageData(0, 0, cols, rows).data;
  const chars = CHARSETS[state.ascii.charset];
  const { contrast, brightness, gamma } = state.preprocess;

  const lines: string[] = [];
  for (let y = 0; y < rows; y++) {
    let line = "";
    let runColor = "";
    let run = "";
    const flush = () => {
      if (!run) return;
      line += state.ascii.colorMode && runColor
        ? `<span style="color:${runColor}">${run}</span>`
        : run;
      run = "";
    };
    for (let x = 0; x < cols; x++) {
      const i = (y * cols + x) * 4;
      let r = d[i] / 255, g = d[i + 1] / 255, b = d[i + 2] / 255;
      r = Math.min(1, Math.max(0, Math.pow(Math.max((r + brightness - 0.5) * contrast + 0.5, 0), 1 / gamma)));
      g = Math.min(1, Math.max(0, Math.pow(Math.max((g + brightness - 0.5) * contrast + 0.5, 0), 1 / gamma)));
      b = Math.min(1, Math.max(0, Math.pow(Math.max((b + brightness - 0.5) * contrast + 0.5, 0), 1 / gamma)));
      let l = r * 0.299 + g * 0.587 + b * 0.114;
      if (state.ascii.invert) l = 1 - l;
      const ch = escapeHtml(chars[Math.min(chars.length - 1, Math.floor(l * chars.length))]);
      if (state.ascii.colorMode) {
        const color = `rgb(${Math.round(r * 255)},${Math.round(g * 255)},${Math.round(b * 255)})`;
        if (color !== runColor) { flush(); runColor = color; }
      }
      run += ch;
    }
    flush();
    lines.push(line);
  }

  const css = `.saundarya-ascii{margin:0;padding:24px;background:#050505;color:${state.ascii.tint};font-family:"JetBrains Mono",ui-monospace,Menlo,Consolas,monospace;font-size:10px;line-height:1.05;letter-spacing:0;white-space:pre;overflow:auto}`;
  return `<!-- Generated by Saundarya Studio · ASCII ${state.ascii.charset} · ${cols}×${rows} -->
<style>${css}</style>
<pre class="saundarya-ascii">${lines.join("\n")}</pre>`;
}