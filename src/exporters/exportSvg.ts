"use client";

import type { StudioState } from "@/store/useStudioStore";
import { getPaletteColors, hexToRgb255 } from "@/data/palettes";

function drawGrid(source: HTMLCanvasElement, cols: number, rows: number): Uint8ClampedArray {
  const c = document.createElement("canvas");
  c.width = cols;
  c.height = rows;
  const ctx = c.getContext("2d", { willReadFrequently: true })!;
  const scale = Math.max(cols / source.width, rows / source.height);
  ctx.drawImage(source, (cols - source.width * scale) / 2, (rows - source.height * scale) / 2, source.width * scale, source.height * scale);
  return ctx.getImageData(0, 0, cols, rows).data;
}

function sampleGrid(source: HTMLCanvasElement, cols: number, rows: number): Float32Array {
  const d = drawGrid(source, cols, rows);
  const out = new Float32Array(cols * rows);
  for (let i = 0; i < cols * rows; i++) {
    out[i] = (d[i * 4] * 0.299 + d[i * 4 + 1] * 0.587 + d[i * 4 + 2] * 0.114) / 255;
  }
  return out;
}

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

export function exportSvg(state: StudioState, source: HTMLCanvasElement, output?: HTMLCanvasElement | null): string {
  const W = 1200;
  const H = Math.round((W * source.height) / source.width);
  const parts: string[] = [];
  parts.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">`);
  parts.push(`<!-- Generated by Saundarya Studio · ${state.effect} -->`);

  if (state.effect === "halftone") {
    const hp = state.halftone;
    parts.push(`<rect width="${W}" height="${H}" fill="${esc(hp.paper)}"/>`);
    const cell = Math.max(6, (hp.dotSize * W) / 900);
    const cols = Math.min(160, Math.ceil(W / cell));
    const rows = Math.ceil(H / cell);
    const luma = sampleGrid(source, cols, rows);
    const cw = W / cols, ch = H / rows;
    const inks =
      hp.mode === "cmyk"
        ? [hp.inkC, hp.inkM, hp.inkY, hp.inkK]
        : hp.mode === "duotone"
          ? [hp.duotoneB]
          : [hp.inkK];
    inks.forEach((ink, pass) => {
      parts.push(`<g fill="${esc(ink)}"${inks.length > 1 ? ' style="mix-blend-mode:multiply"' : ""}>`);
      const shift = pass * 0.6;
      for (let y = 0; y < rows; y++) {
        for (let x = 0; x < cols; x++) {
          const l = luma[y * cols + x];
          const value = 1 - l;
          const r = Math.sqrt(Math.max(0, value)) * Math.min(cw, ch) * 0.62;
          if (r < 0.35) continue;
          const cx = (x + 0.5) * cw + shift;
          const cy = (y + 0.5) * ch - shift;
          if (hp.shape === "line") {
            parts.push(`<rect x="${(cx - cw / 2).toFixed(1)}" y="${(cy - r / 2).toFixed(1)}" width="${cw.toFixed(1)}" height="${r.toFixed(1)}"/>`);
          } else {
            const ry = hp.shape === "ellipse" ? r * 0.72 : r;
            parts.push(`<ellipse cx="${cx.toFixed(1)}" cy="${cy.toFixed(1)}" rx="${r.toFixed(1)}" ry="${ry.toFixed(1)}"/>`);
          }
        }
      }
      parts.push(`</g>`);
    });
  } else if (state.effect === "dither") {
    const palette = getPaletteColors(state.paletteId, state.customColors, state.imagePalette);
    const cell = Math.max(4, (state.dither.pixelSize * W) / 900);
    const cols = Math.min(180, Math.ceil(W / cell));
    const rows = Math.ceil(H / cell);
    const cw = W / cols, ch = H / rows;
    const bayer = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
    const rgb = drawGrid(source, cols, rows);
    const cols255 = palette.map(hexToRgb255);
    const groups = new Map<number, string[]>();
    for (let y = 0; y < rows; y++) {
      for (let x = 0; x < cols; x++) {
        const i = (y * cols + x) * 4;
        const off = (bayer[(y % 4) * 4 + (x % 4)] / 16 - 0.5) * 255 * state.dither.spread;
        let r = rgb[i] + off, g = rgb[i + 1] + off, b = rgb[i + 2] + off;
        if (state.dither.invert) { r = 255 - r; g = 255 - g; b = 255 - b; }
        let best = 0, bd = Infinity;
        for (let k = 0; k < cols255.length; k++) {
          const c = cols255[k];
          const dd = (r - c[0]) ** 2 + (g - c[1]) ** 2 + (b - c[2]) ** 2;
          if (dd < bd) { bd = dd; best = k; }
        }
        const rect = `<rect x="${(x * cw).toFixed(1)}" y="${(y * ch).toFixed(1)}" width="${(cw + 0.5).toFixed(1)}" height="${(ch + 0.5).toFixed(1)}"/>`;
        const bucket = groups.get(best);
        if (bucket) bucket.push(rect);
        else groups.set(best, [rect]);
      }
    }
    parts.push(`<rect width="${W}" height="${H}" fill="${esc(palette[0])}"/>`);
    for (const [k, rects] of groups) {
      parts.push(`<g fill="${esc(palette[k])}">`);
      parts.push(...rects);
      parts.push(`</g>`);
    }
  } else if (state.effect === "ascii" && output) {
    parts.push(`<rect width="${W}" height="${H}" fill="#050505"/>`);
    const cell = Math.max(8, (state.ascii.cellSize * W) / 900);
    const cols = Math.min(140, Math.ceil(W / cell));
    const rows = Math.ceil(H / cell);
    const luma = sampleGrid(source, cols, rows);
    const rgb = state.ascii.colorMode ? drawGrid(source, cols, rows) : null;
    const chars = " .:-=+*#%@";
    const cw = W / cols, ch = H / rows;
    parts.push(`<g font-family="monospace" font-size="${(ch * 1.05).toFixed(1)}"${rgb ? "" : ` fill="${esc(state.ascii.tint)}"`}>`);
    for (let y = 0; y < rows; y++) {
      for (let x = 0; x < cols; x++) {
        const l = state.ascii.invert ? 1 - luma[y * cols + x] : luma[y * cols + x];
        const ch2 = chars[Math.min(chars.length - 1, Math.floor(l * chars.length))];
        if (ch2 === " ") continue;
        let fill = "";
        if (rgb) {
          const i = (y * cols + x) * 4;
          fill = ` fill="rgb(${Math.max(20, rgb[i])},${Math.max(20, rgb[i + 1])},${Math.max(20, rgb[i + 2])})"`;
        }
        parts.push(`<text x="${(x * cw).toFixed(1)}" y="${((y + 1) * ch).toFixed(1)}"${fill}>${esc(ch2)}</text>`);
      }
    }
    parts.push(`</g>`);
  } else if (output) {
    // mesh / fallback: posterized mosaic of the live output
    const cols = 64;
    const rows = Math.max(8, Math.round((cols * H) / W));
    const c = document.createElement("canvas");
    c.width = cols;
    c.height = rows;
    const ctx = c.getContext("2d", { willReadFrequently: true })!;
    ctx.drawImage(output, 0, 0, cols, rows);
    const d = ctx.getImageData(0, 0, cols, rows).data;
    const cw = W / cols, ch = H / rows;
    for (let y = 0; y < rows; y++) {
      for (let x = 0; x < cols; x++) {
        const i = (y * cols + x) * 4;
        parts.push(`<rect x="${(x * cw).toFixed(1)}" y="${(y * ch).toFixed(1)}" width="${(cw + 0.5).toFixed(1)}" height="${(ch + 0.5).toFixed(1)}" fill="rgb(${d[i]},${d[i + 1]},${d[i + 2]})"/>`);
      }
    }
  }
  parts.push(`</svg>`);
  return parts.join("\n");
}